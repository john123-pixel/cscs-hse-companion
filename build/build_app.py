"""Embeds data/app_data.json into index.html between the APP_DATA markers, then writes:
  - sw.js: offline cache for the hosted copy (index.html + images folder)
  - dist/CSCS-HSE-Companion.html: one standalone file with every image embedded (works offline, no images folder needed)
"""
import base64, json, os, re
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
html = open(f'{R}/index.html', encoding='utf-8').read()
data = open(f'{R}/data/app_data.json', encoding='utf-8').read().replace('</', '<\\/')
new = re.sub(r'/\*APP_DATA_START\*/.*?/\*APP_DATA_END\*/', lambda m: '/*APP_DATA_START*/' + data + '/*APP_DATA_END*/', html, flags=re.S)
assert new != html or '/*APP_DATA_START*/' + data in html
open(f'{R}/index.html', 'w', encoding='utf-8').write(new)
print('index.html', os.path.getsize(f'{R}/index.html'), 'bytes')

# Every image the page refers to must exist (a missing image is a build error, brief 7.1)
refs = sorted(set(re.findall(r'images/(?:q|login)/[A-Za-z0-9_.-]+\.(?:webp|jpe?g|png)', new)))
missing = [r for r in refs if not os.path.exists(f'{R}/{r}')]
assert not missing, missing

# Offline cache for the hosted copy
version = re.search(r'appVersion:\s*"([^"]+)"', new).group(1)
sw = f'''/* Offline cache for the HS&E Companion (generated by build/build_app.py). */
const CACHE = "hse-companion-{version}";
const FILES = {json.dumps(['./', 'index.html'] + refs)};
self.addEventListener("install", e => {{ e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting())); }});
self.addEventListener("activate", e => {{ e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); }});
self.addEventListener("fetch", e => {{
  if(e.request.method !== "GET") return;
  e.respondWith(caches.match(e.request, {{ignoreSearch: true}}).then(hit => hit || fetch(e.request).then(res => {{
    if(res.ok && new URL(e.request.url).origin === location.origin){{ const copy = res.clone(); caches.open(CACHE).then(c => c.put(e.request, copy)); }}
    return res;
  }}).catch(() => caches.match("index.html"))));
}});
'''
open(f'{R}/sw.js', 'w').write(sw)

# Standalone single file
def uri(path):
    ext = path.rsplit('.', 1)[1].lower()
    mime = {'webp': 'image/webp', 'jpg': 'image/jpeg', 'jpeg': 'image/jpeg', 'png': 'image/png'}[ext]
    return f'data:{mime};base64,' + base64.b64encode(open(f'{R}/{path}', 'rb').read()).decode()
one = new
for r in refs:
    one = one.replace(r, uri(r))
one = one.replace('<html lang="en-GB">', '<html lang="en-GB" data-standalone>', 1)
os.makedirs(f'{R}/dist', exist_ok=True)
open(f'{R}/dist/CSCS-HSE-Companion.html', 'w', encoding='utf-8').write(one)
print('images embedded', len(refs), '| dist/CSCS-HSE-Companion.html', os.path.getsize(f'{R}/dist/CSCS-HSE-Companion.html'), 'bytes')
